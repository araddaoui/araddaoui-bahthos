function buildDalilFallback(activeSources: any[]): string {
  const sourceCount = activeSources.length;
  const title = (source: any, index: number) =>
    (source?.title || `المصدر ${index + 1}`).replace(/\.[a-z0-9]{2,4}$/i, "").trim();
  const summary = (source: any) =>
    (source?.summary || source?.content || "").replace(/\s+/g, " ").trim();
  const titles = activeSources.map(title).join("، ");
  const first = summary(activeSources[0]).slice(0, 520) || "لا يتوفر في هذا المصدر ملخص قابل للاقتباس المباشر.";
  const second = summary(activeSources[1]).slice(0, 520) || "لا يتوفر في هذا المصدر ملخص قابل للاقتباس المباشر.";
  const additional = activeSources.slice(2, 5).map((source, index) =>
    `المصدر ${index + 3} «${title(source, index + 2)}» يضيف إلى مجموعة الأدلة المقتطف الآتي: «${summary(source).slice(0, 300) || "لا يتوفر ملخص كافٍ"}».`
  ).join(" ");

  return [
    `تتناول هذه الإحاطة المقارنة ${sourceCount} مصادر راهنة هي: ${titles}. وتُقرأ هذه المجموعة بوصفها مجموعة بحثية واحدة، لا كسلسلة ملخصات منفصلة؛ لذلك تركز المقارنة على ما يتقاطع فيه تعريف المشكلة، وما يختلف فيه مستوى التحليل، وما الذي تضيفه كل وثيقة إلى فهم الوثائق الأخرى.`,
    `يقدم المصدر الأول «${title(activeSources[0], 0)}» مادةً دالةً على مسار التحليل من خلال المقتطف الآتي: «${first}». ويقدم المصدر الثاني «${title(activeSources[1], 1)}» مادةً أخرى: «${second}». ولا تكمن قيمة الجمع بينهما في تكرار مضمون كل واحد، بل في اختبار ما إذا كانت المفاهيم والأدلة الواردة في المقتطفين تنتمي إلى السؤال نفسه، أو تكشف اختلافاً في النطاق أو المنهج أو مستوى التفسير.`,
    `تكشف المقارنة الأولية أن العلاقة بين المصادر لا ينبغي أن تُحسم بعبارة اتفاق أو تعارض قبل فحص السياق الذي صيغت فيه كل حجة. فإذا كان أحد النصين يشرح البنية أو المفهوم، وكان الآخر يصف الأثر أو الحالة، فإن التباين بينهما قد يكون اختلافاً في زاوية النظر لا تناقضاً تجريبياً؛ أما إذا عالجا المسألة نفسها بمعايير مختلفة، فتظل النتيجة المقارنة مشروطة بحدود الأدلة المتاحة.`,
    additional || `تستكمل المصادر الأخرى الصورة بإضافة زوايا أو شواهد لا تظهر في المقتطفين الأولين، وتحتاج هذه الإضافات إلى قراءتها ضمن مجموع الأدلة لا بمعزل عنه.`,
    `ومن الناحية المنهجية، تفرض المجموعة الحالية التمييز بين ما تصرح به النصوص، وما يمكن استنتاجه بحذر من تقاطعها. لذلك لا تُعد هذه الإحاطة دليلاً على علاقة سببية ما لم تسندها المصادر صراحة، ولا تُحوّل اختلاف المصطلحات أو السياقات إلى اختلاف في النتائج من دون قرينة مباشرة، كما تُترك النقاط التي لا تعالجها الوثائق معلقة بوصفها فجوات بحثية حقيقية.`,
    `الخلاصة التحليلية أن قيمة هذه المجموعة تكمن في إمكان وصل مستوياتها المختلفة داخل قراءة واحدة: يُستفاد من المصدر الذي يحدد الإطار في تفسير المصدر الذي يعرض الحالة، ويُستخدم المصدر الذي يعرض الحالة لاختبار مدى صلاحية الإطار في الواقع. وتظل الأسئلة المتعلقة بحدود المقارنة، وبالأدلة التي لا تظهر في المصادر الحالية، بحاجة إلى مصادر إضافية قبل بناء حكم نهائي.`,
    `تستند هذه الإحاطة إلى المصادر الحالية في هذا المشروع حصراً، ولا تستعير معلومات من مشاريع سابقة أو من معرفة خارجية.`
  ].join("\n\n");
}

